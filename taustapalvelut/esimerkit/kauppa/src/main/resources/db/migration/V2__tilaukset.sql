CREATE TABLE tilaus (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiakas VARCHAR(50) NOT NULL,
    luotu   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE tilaus_rivi (
    tilaus          BIGINT NOT NULL REFERENCES tilaus (id),
    rivi            INT    NOT NULL,
    tuote_id        BIGINT NOT NULL REFERENCES tuote (id),
    maara           INT    NOT NULL CHECK (maara > 0),
    hinta_sentteina BIGINT NOT NULL,
    PRIMARY KEY (tilaus, rivi)
);

CREATE INDEX tilaus_asiakas ON tilaus (asiakas);
