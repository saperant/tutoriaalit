CREATE TABLE tuote (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nimi            VARCHAR(100) NOT NULL UNIQUE,
    hinta_sentteina BIGINT NOT NULL CHECK (hinta_sentteina >= 0),
    saldo           INT    NOT NULL CHECK (saldo >= 0),
    versio          BIGINT NOT NULL DEFAULT 0
);
